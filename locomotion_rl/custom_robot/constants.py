"""Constants of the custom quadruped (urdf_robot_description, src/custom_robot_desc).

Everything lives on one class, so a single import gives access to all of it:

    from locomotion_rl.custom_robot.constants import consts
    consts.FEET_SITES, consts.TORQUE_LIMIT, ...

The class is never instantiated; the attributes are class attributes (the same `consts.NAME` spelling the Playground Go1
code uses for its constants module).

Values come from the MJCF generated by the custom_robot_mjcf package (itself generated from the URDF),
from custom_robot_desc/config/gait/gait.yaml and from the servo data sheet. This file has no ROS or MuJoCo
dependency. Where a value is also stored in the MJCF it is repeated here so the environment can assert
agreement; the MJCF/URDF stays the source of truth for geometry and inertia.
"""

import itertools

from etils import epath


class CustomRobotConstants:
    # --- files ---------------------------------------------------------------------------------------
    ROOT_PATH = epath.Path(__file__).parent
    XML_DIR = ROOT_PATH / "xmls"
    # MJX files, written by scripts/gen_custom_mjx.py (do not hand-edit): the robot with feet-only collision, and the scene
    # that includes it (floor, light, foot-contact sensors). Meshes (visual only) are in XML_DIR / "assets".
    ROBOT_XML = XML_DIR / "custom_robot_mjx.xml"
    FLAT_TERRAIN_XML = XML_DIR / "scene_mjx_flat_terrain.xml"
    ROUGH_TERRAIN_XML = XML_DIR / "scene_mjx_rough_terrain.xml"      # fractal heightfield (assets/terrain.png), see terrain.py

    BLOCK_TERRAIN_XML = XML_DIR / "scene_mjx_block_terrain.xml"      # grid of random-height cuboids (assets/terrain_blocks.png)

    @classmethod
    def task_to_xml(cls, task: str):
        return {"flat_terrain": cls.FLAT_TERRAIN_XML, "rough_terrain": cls.ROUGH_TERRAIN_XML,
                "block_terrain": cls.BLOCK_TERRAIN_XML}[task]

    # --- names in the MJCF -----------------------------------------------------------------------------
    ROOT_BODY = "base_link"      # free body; its frame is the URDF base_link frame (x forward, y left, z up)
    KEYFRAME = "stand_bent"      # default pose of the RL environments: legs bent as CHAMP walks (STAND_BENT_*)
    KEYFRAME_STRAIGHT = "stand"  # all joints at STAND_JOINTS (legs straight), base at STAND_BASE_HEIGHT

    # The model's first joint is a free joint (7 qpos, 6 dof) that custom_robot_mjcf adds to base_link; the 12 leg joints
    # follow. So qpos[7:], qvel[6:], jnt_range[1:], and ctrl / actuators / actions all share ONE order (JOINT_NAMES).
    ROOT_JOINT = "root"
    NUM_ROOT_QPOS = 7
    NUM_ROOT_DOF = 6

    # Leg order = model joint order (URDF link order), NOT CHAMP's lf, rf, lh, rh. The generator makes the actuators follow
    # it and fails if they do not, so this holds for qpos, qvel, ctrl, actions and every per-foot tuple below.
    LEGS = ("lh", "lf", "rh", "rf")
    JOINT_ROLES = ("hip", "upper_leg", "lower_leg")
    # CAD-export joint names, per leg: (hip, upper leg, lower leg). Same as custom_robot_desc/config/joints/joints.yaml.
    LEG_JOINTS = {
        "lf": ("Revolute 9", "Revolute 18", "Revolute 19"),
        "rf": ("Revolute 13", "Revolute 20", "Revolute 21"),
        "lh": ("Revolute 8", "Revolute 14", "Revolute 15"),
        "rh": ("Revolute 12", "Revolute 16", "Revolute 17"),
    }
    JOINT_NAMES = tuple(itertools.chain.from_iterable(map(LEG_JOINTS.__getitem__, LEGS)))   # joint = actuator order, 12 entries
    ACTUATOR_NAMES = JOINT_NAMES                           # position actuators are named like their joint
    NUM_JOINTS = len(JOINT_NAMES)

    FEET_SITES = tuple(f"{leg}_foot_site" for leg in LEGS)       # foot tip points on the lower-leg bodies
    # MJX scene only: the foot is the only collision geom besides the floor.
    FLOOR_GEOM = "floor"
    FEET_GEOMS = tuple(f"{leg}_foot" for leg in LEGS)            # cylinders, see FOOT_* below
    FEET_FLOOR_FOUND_SENSOR = tuple(f"{leg}_foot_floor_found" for leg in LEGS)   # 1 while the foot touches the floor, else 0

    IMU_SITE = "imu"             # at the URDF imu_joint position, axes = base_link axes (see MANUAL_EDITS.md)
    BASE_ORIGIN_SITE = "base_origin"
    MAX_JOINT_VELOCITY_NUMERIC = "max_joint_velocity"      # <custom><numeric> in the MJCF

    # Sensors. All but the touch sensors and base_* are on the imu site (so in base_link axes unless noted).
    # What a policy could also get on the real robot: gyro, accelerometer, upvector (from the IMU orientation) and joint
    # state. The velocities and foot positions below are privileged (simulation only), meant for the critic and rewards.
    GYRO_SENSOR = "imu_gyro"                  # angular velocity, imu axes
    ACCELEROMETER_SENSOR = "imu_acc"          # specific force (gravity reads +9.81 on the up axis at rest), imu axes
    IMU_QUAT_SENSOR = "imu_quat"              # imu orientation in the world
    UPVECTOR_SENSOR = "upvector"              # the imu z axis written in WORLD axes: (0, 0, 1) when upright, z component
                                              # = cos(tilt), < 0 when flipped over. Used for the fall check and orientation cost
    GLOBAL_LINVEL_SENSOR = "global_linvel"    # linear velocity of the imu point, WORLD axes
    GLOBAL_ANGVEL_SENSOR = "global_angvel"    # angular velocity, WORLD axes
    LOCAL_LINVEL_SENSOR = "local_linvel"      # linear velocity of the imu point, imu (= base) axes
    FEET_POS_SENSOR = tuple(f"{leg}_foot_pos" for leg in LEGS)       # foot position in imu axes (relative to the imu site)
    FEET_GLOBAL_LINVEL_SENSOR = tuple(f"{leg}_foot_global_linvel" for leg in LEGS)   # foot linear velocity, WORLD axes (feet slip)
    FEET_TOUCH_SENSORS = tuple(f"{leg}_foot_touch" for leg in LEGS)
    BASE_POS_SENSOR = "base_pos"              # base_link origin in the world (site base_origin)
    BASE_LINVEL_SENSOR = "base_linvel"        # its linear velocity, world axes

    # --- body ------------------------------------------------------------------------------------------
    TOTAL_MASS = 0.6477          # kg, whole robot (MJCF body_subtreemass of base_link)
    THIGH_LENGTH = 0.043         # m, upper leg
    SHANK_LENGTH = 0.076         # m, lower leg
    IMU_POS = (-0.04075, -0.008, 0.043)    # m in base_link; the real IMU is mounted X down / Y right (Z backward)
    # Foot = cylinder on the end of the lower-leg bar, axis along the knee axis (body y), fitted to the URDF mesh by
    # gen_custom_mjx.py (the mesh tip is a 24-gon, within 0.01 mm of this cylinder). Centre in the lower-leg frame:
    # (0, -FOOT_CENTER_Y on the left legs / +FOOT_CENTER_Y on the right legs, FOOT_CENTER_Z).
    FOOT_RADIUS = 0.004          # m
    FOOT_HALF_LENGTH = 0.004     # m (length 8 mm)
    FOOT_CENTER_Y = 0.012        # m
    FOOT_CENTER_Z = -0.07189     # m

    # --- servo: Feetech SC-009 -------------------------------------------------------------------------
    # Torque and speed limits as set in the URDF <limit> and enforced by the MJCF (forcerange, rate limit of the targets).
    JOINT_RANGE = 2.617994       # rad, +- from the zero pose (150 deg)
    TORQUE_LIMIT = 0.2255        # N m per joint (2.3 kg cm; URDF effort, MJCF forcerange)
    MAX_JOINT_VELOCITY = 10.47   # rad/s per joint (URDF velocity, 100 RPM)
    SERVO_BAUD = 1_000_000       # serial bus; sets how fast all 12 servos can be written/read per control step
    SERVO_DEFAULT_P = 15         # factory P / D register values (servo units; not N m/rad)
    SERVO_DEFAULT_D = 15
    SERVO_BACKLASH = 0.008

    # --- actuator and joint model in the MJCF ----------------------------------------------------------
    # <position kp kv>: tau = KP (target - q) - KV qdot, clamped to +-TORQUE_LIMIT. KP = 2 was picked from a sweep
    # (kp 10 is bang-bang, kp 1 cannot follow the CHAMP gait, 2 almost never saturates).
    ACTUATOR_KP = 2.0            # N m/rad
    ACTUATOR_KV = 0.05           # N m s/rad
    JOINT_DAMPING = 0.002        # N m s/rad
    JOINT_ARMATURE = 0.0005      # kg m^2
    JOINT_FRICTIONLOSS = 0.0005  # N m
    FRICTION = (0.8, 0.005, 0.0001)        # geom sliding, torsional, rolling
    SIM_TIMESTEP = 0.001         # s, CPU MJCF. MJX will likely need a larger one; re-check when the scene is ported

    # --- stand pose ------------------------------------------------------------------------------------
    STAND_JOINTS = (0.0, 0.0, 0.0)         # hip, upper leg, lower leg (the URDF zero pose)
    STAND_BASE_HEIGHT = 0.09946  # m, base_link origin above the floor in the keyframe
    STAND_FOOT_CLEARANCE = 0.001 # m, lowest foot point above the floor in the keyframe
    # Bent-leg pose: the foot sits under the hip CHAMP_NOMINAL_HEIGHT below the base, thigh back and shank forward (knee ">>").
    # Solved by custom_robot_mjcf (IK on the compiled model); the legs agree within 1e-4 rad, the mean is used here.
    STAND_BENT_JOINTS = (0.0, 0.8799, -1.3368)   # hip, upper leg, lower leg [rad]
    STAND_BENT_BASE_HEIGHT = 0.0760              # m, base_link origin above the floor (CHAMP_NOMINAL_HEIGHT + clearance)

    # --- CHAMP reference gait (gait.yaml; first-guess values, not verified) -----------------------------
    # The controller clamps /cmd_vel to these; the metrics cap the commanded motion the same way.
    CHAMP_MAX_LINEAR_VELOCITY_X = 0.15     # m/s
    CHAMP_MAX_LINEAR_VELOCITY_Y = 0.08     # m/s
    CHAMP_MAX_ANGULAR_VELOCITY_Z = 1.0     # rad/s
    CHAMP_NOMINAL_HEIGHT = 0.075           # m, base_link above the ground while walking (knees bent, not the stand pose)
    CHAMP_SWING_HEIGHT = 0.02              # m
    CHAMP_STANCE_DURATION = 0.15           # s


consts = CustomRobotConstants
